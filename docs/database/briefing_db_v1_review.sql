-- SAS Briefing DB V1 / REVIEW-ONLY MIGRATION
-- NOT applied to production by this commit.
-- Built over sas.developments and existing sas.team_members.
begin;

create table sas.briefing_editions (
 id uuid primary key default gen_random_uuid(),
 edition_no bigint generated by default as identity unique,
 slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
 edition_date date not null unique,
 window_start timestamptz not null,
 window_end timestamptz not null,
 checked_at timestamptz,
 title_ar text not null default 'الإحاطة اليمنية' check (char_length(title_ar) between 4 and 220),
 lead_ar text not null default '',
 analysis_ar text not null default '',
 watchpoints_ar text not null default '',
 methodology_ar text not null default '',
 coverage_note_ar text not null default '',
 status text not null default 'draft' check (status in ('draft','review','approved','published','withdrawn')),
 version_no integer not null default 1 check (version_no >= 1),
 created_by uuid references auth.users(id),
 reviewed_by uuid references auth.users(id),
 approved_by uuid references auth.users(id),
 published_by uuid references auth.users(id),
 reviewed_at timestamptz,
 approved_at timestamptz,
 published_at timestamptz,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 constraint briefing_valid_window check (window_end > window_start),
 constraint briefing_publication_timing check (status <> 'published' or (published_at is not null and approved_at is not null and checked_at is not null))
);

create table sas.briefing_items (
 id uuid primary key default gen_random_uuid(),
 edition_id uuid not null references sas.briefing_editions(id) on delete cascade,
 development_id uuid not null references sas.developments(id),
 placement text not null check (placement in ('lead','major','ledger')),
 position integer not null check (position >= 1),
 headline_override_ar text,
 why_it_matters_ar text not null default '',
 what_changed_ar text not null default '',
 context_ar text not null default '',
 editorial_note_ar text not null default '',
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 unique (edition_id, development_id),
 unique (edition_id, placement, position),
 constraint headline_override_length check (headline_override_ar is null or char_length(headline_override_ar) <= 220)
);

create table sas.briefing_revisions (
 id uuid primary key default gen_random_uuid(),
 edition_id uuid not null references sas.briefing_editions(id) on delete cascade,
 version_no integer not null check (version_no > 0),
 change_kind text not null check (change_kind in ('snapshot','correction','withdrawal')),
 reason_ar text not null check (char_length(trim(reason_ar)) >= 6),
 snapshot jsonb not null,
 changed_by uuid not null references auth.users(id),
 changed_at timestamptz not null default now(),
 unique (edition_id, version_no)
);

create index briefing_editions_published_idx on sas.briefing_editions(published_at desc) where status='published';
create index briefing_items_development_idx on sas.briefing_items(development_id);
create index briefing_revisions_recent_idx on sas.briefing_revisions(edition_id,changed_at desc);

alter table sas.briefing_editions enable row level security;
alter table sas.briefing_items enable row level security;
alter table sas.briefing_revisions enable row level security;

-- No table grants are opened to anon/authenticated in V1.
-- Deliberately no direct browser write paths or public-read policy:
-- reviewed SECURITY DEFINER RPCs are required before enabling publication.
revoke all on table sas.briefing_editions,sas.briefing_items,sas.briefing_revisions from public,anon,authenticated;
revoke all on sequence sas.briefing_editions_edition_no_seq from public,anon,authenticated;

comment on table sas.briefing_editions is 'Editorial daily briefing edition; production access only via reviewed RPCs.';
comment on table sas.briefing_items is 'Edition-specific ordering and interpretation of existing developments.';
comment on table sas.briefing_revisions is 'Immutable-by-contract revision snapshots; future RPC must enforce append-only behavior.';

commit;
